// THE MENU SEED. Plain typed objects, checked twice:
//  - at compile time by `satisfies` (a typo in a field name is an error), and
//  - at runtime by DishSchema.parse in lib/data.ts (prices are whole kobo,
//    IDs have the right shape, option IDs are unique, and so on).
// Prices are in kobo: 450000 = ₦4,500.
//
// `kitchenNotes` are instructions for the kitchen. They are server-only:
// lib/data.ts strips them before any dish leaves the server, and the order
// action prints them on the kitchen ticket.

